    <h4>What is e-Passport? </h4>
	</div>
<p align="justify">The e-Passport is a highly secure travel document. It has an electronic chip embedded in one of the passport pages, which will be used to store biometric information about the holder. The chip contains data that will verify the passport holder’s identity and will include the biometrics of the passport holder, the personal data found on the data page of the passport, a unique identification number and a digital signature. An e-passport has a contactless (NFC) chip on it which means that those passports can be read electronically. The newly launched e-Passports in Pakistan are in compliance with the United Nations’ ICAO standards. </p>
<div class="alert alert-dark mb-2" role="alert">
    <h4>Salient Features</h4>
	</div>
<ul> 
<li>Chip based data storage with laser engraving</li>
<li>Multiple security feature including IR & UV</li>
<li>e-Gate facility for immigration</li>
<li>ICAO compliant standards</li>
<li>Real time match of personalized data at airports </li>
</ul>
<div class="alert alert-primary mb-2" role="alert">
   <h4>Benefits of Pakistan e-Passport</h4>
	</div>
<p align="justify">E-Passports are already in use in more than 150 countries worldwide. Several countries have switched to the e-Passport due to the increasing need for efficient and better border security.</p>
<p align="justify">Pakistan e-Passport holders can benefit from the e-gate facility at all airports around the world. It will also help eliminate all the hurdles in the ongoing manual system and will aid Pakistani applicants to process online applications conveniently. Since the e-Passport carries out various forms of security checks, extending benefits to overseas Pakistanis will ultimately benefit the country. </p>
<div class="alert alert-success mb-2" role="alert">
  <h4>Pakistan e-Passport application process</h4>
	</div>
<p align="justify">The application process for the Pakistan e-Passport will be similar to acquiring a traditional passport. <!--Initially, the e-passport facility will only be available for diplomatic and government officials of Pakistan.-->
Applicants will receive the e-Passports after the manufacturing process is complete. The documents required for an e-Passport will be similar to that of a Machine Readable Passport (MRP). </p>
<div class="alert alert-content danger mb-2" role="alert">
    <h4>Important Instructions</h4>
	</div>
	<p>The following conditions are mandatory for applying the e-Passport at RPOs :</p>
<ul> 
<li>First Name and Last Name are Required</li>
<li>First Name allowed up to 50 characters</li>
<li>Last Name allowed up to 40 characters</li>
<li>Relative (Father/Husband/Guardian) Name allowed up to 40 characters</li>

