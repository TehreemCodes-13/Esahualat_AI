					<p align="justify">Through Online Application, the applicant will have to create his/ her login. Once user credentials are verified and a login account is created, the applicant can proceed further to process their passport applications. The applicant has the choice to save the application at any stage. The application works in a wizard type and applicants will be asked to provide their detail including demographic data, biometric data along with <a href="https://onlinemrp.dgip.gov.pk/supp-docs/" class="styleTextHeadings"><b class="text-danger">supporting documents</b></a>. </P>
