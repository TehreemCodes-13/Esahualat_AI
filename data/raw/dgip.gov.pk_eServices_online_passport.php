<h5 class="mb-1">2-Verification of Documents: </h5>
</div>	
<P align="justify">All submitted applications are reviewed at DGIP Headquarters and the decision is based on the provided documents. The passport officer would either approve for onward processing or mark the applications for further verification to the nearest Mission / RPO. Once all codal formalities are complete, the application will be approved for passport printing/ dispatch to the applicant.</P>
<div class="alert alert-success border-success  mb-3" role="alert">
<h5 class="mb-1">3-Application Status Intimation:</h5>
