      <td><p align="justify"><b>Machine-Readable Zone (MRZ):</b> MRPs include an MRZ that can be read by optical scanners at passport control. This zone contains the passport holder’s personal information in a standardized format.</p>
<p align="justify"><b>Data Page:</b> The data page includes the holder's photo, name, nationality, date of birth, and other relevant information.</p>
<p align="justify"><b>Security Features:</b> MRPs have various security features, such as watermarks, holograms, and UV-visible elements to prevent counterfeiting.</p>
<p align="justify"><b>Paper-Based:</b> Primarily a physical document without embedded electronic components.</p>
</td>
      <td><p align="justify"><b>Embedded Microchip:</b> This contains a microchip embedded in the passport cover, which stores the holder's personal data, including biometric information such as fingerprints and a digital photograph.</p>
<p align="justify"><b>Enhanced Security:</b> Offers advanced security features including digital signatures, encryption, and public key infrastructure (PKI) to prevent unauthorized access and tampering.</p>
<p align="justify"><b>Contactless Communication:</b> The microchip can be read by RFID readers at passport control, facilitating quicker and more secure verification.</p>
<p align="justify"><b>Comprehensive Biometric Data:</b> Stores more detailed biometric data than MRPs, enhancing identity verification processes.</p>
</td>
    </tr>
