	<h5 id="difference"><strong><span style="color:red">Q-15- What is the difference between <span class="text-success">Machine Readable Passport (MRP)</span> and <span class="text-primary">e-Passport?</span></span></strong></h5>
 <p align="justify"><strong>Answer: </strong>  Both are issued by the Government of Pakistan, but they offer different features and benefits. This comparison highlights the distinctions and advantages of each type.</p>								
	<div class="table-responsive">
	<table class="table table-bordered">
  <thead>
    
       <tr class="table-warning">
