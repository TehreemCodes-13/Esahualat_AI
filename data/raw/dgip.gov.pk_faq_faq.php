 <p><strong>Answer: </strong>  <a href="..//passport/ordinary-passport.php#docs-required">Click this link to check required documents</a></p>
<hr>
<h5><strong>Q-3-What is the fee of normal passport?</span></strong></h5>
 <p><strong>Answer: </strong> The Fee for <b class="text-danger">Normal</b> Passport having 36 Pages is <b class="text-danger">Rs. 4500/-</b> only.</p>
<hr>
<h5><strong>Q-4-What is the fee of urgent passport?</span></strong></h5>
 <p><strong>Answer: </strong> The Fee for <b class="text-danger">Urgent</b> Passport having 36 Pages is <b class="text-danger">Rs. 7500/-</b> only.</p>
<hr>
<h5><strong>Q-5-What is the processing time of normal passport?</strong></h5>
 <p><strong>Answer: </strong> Normal fee passport will be issued after <b class="text-danger">21</b> working days.</p>
<hr>
<h5><strong>Q-6-What is the processing time of urgent passport?</strong></h5>
 <p><strong>Answer: </strong> Urgent fee passport will be issued in <b class="text-danger">05</b> working days.</p>
 <hr>
<h5><strong>Q-7-What is the processing time of Fast Track passport?</strong></h5>
 <p><strong>Answer: </strong> Fast Track fee passport will be issued in <b class="text-danger">02</b> working days.</p>
<hr>
<h5><strong>Q-8-How can I modify my name on Machine Readable Passport(MRP)?</strong></h5>
 <p><strong>Answer: </strong> To update your name in your passport, you will need to submit the <b class="text-danger">revised original CNIC</b> (Computerized National Identity Card) that reflects the updated name.</p>
 <hr>
 <h5><strong>Q-9-How can I modify my date of birth on Machine Readable Passport (MRP)?</strong></h5>
 <p align="justify"><strong>Answer: </strong> To request a change in your date of birth, you need to submit the <b class="text-danger">revised original CNIC</b> (Computerized National Identity Card) that reflects the updated date of birth. Additionally, for further verification, you may provide a birth certificate or a Matriculation degree (optional).</p>
 <hr>
 <h5><strong>Q-10-How can I change photograph on Machine Readable Passport(MRP)?</strong></h5>
 <p align="justify"><strong>Answer: </strong> To update the photograph in your passport, a new passport will be issued to you in accordance with the policy. You will need to pay the applicable fresh fee for the issuance of the new passport, and your previous passport will be cancelled.</p>
  <hr>
  <h5><strong>Q-11-How can overseas Pakistanis renew their passport?</strong></h5>
 <p align="justify"><strong>Answer: </strong> Overseas Pakistanis can renew their passports through the online application portal. To initiate the renewal process, please visit <a href="https://onlinemrp.dgip.gov.pk"><b class="text-danger">https://onlinemrp.dgip.gov.pk</a></b> or the nearest Pakistani Embassy.</p>
   <hr>
   <h5><strong>Q-12-How can I collect my passport?</strong></h5>
 <p align="justify"><strong>Answer: </strong> If you opt for the Home Delivery option, your passport will be conveniently delivered directly to your doorstep. Otherwise, kindly reach out to the concerned Regional Passport Office / Foreign Mission where you submitted your passport application.</p> 
	<hr>
	<h5><strong><span style="color:red">Q-13- When e-Passport issuance will be started at Foreign Missions?</span></strong></h5>
<p align= "justify"><strong>Answer: </strong> Starting <b class="text-danger">August 16, 2023</b>, the <b class="text-danger">e-Passport issuance facility</b>, is now accessible <b>at all field offices nationwide</b>. </b> Previously, this service was exclusively available <b class="text-danger">to residents of Islamabad</b>. In <b>2022</b>, DGI&amp;P initiated the issuance of e-Passports, initially targeting <b>Diplomatic and Official Categories</b> as part of a soft launch. This service will be extended to Foreign Missions in due course of time.</p>
