	</div>
				<ul>
                    <li>The applicant will approach the ECL/BL Desk having Form.</li>
                    <li>The verification against Exit Control List (ECL) and Black List (BL) will be carried out and official on the desk will affix clearance stamp on the data form after checking the record.</li>
