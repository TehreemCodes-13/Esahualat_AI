                 <div class="alert alert-warning border-warning" role="alert">
    <h5><strong class="badge badge-warning">Step 6</strong> – Interview &amp; Decision by Assistant Director</h5>
	</div>
				<ul>
                    <li>Finally, the applicant will appear before Assistant Director / Officer In-charge when his token number appears on the decision counter, along with all the relevant documents and Data Form.</li>
                    <li>The Assistant Director/ Officer In-charge will interview the applicant and satisfy himself with respect to the National Status/credibility of the applicant. Upon his satisfaction, he will allow, “Go ahead” the case, otherwise he can ask for additional documents. If required he will refer the case to Security Agency for determination of National Status of the applicant as citizen of Pakistan.</li>
                    <li>The Assistant Director will defer the case of Applicant below 18 years of age and will hand over the printed form to the applicant for attestation of his data form, from a Government Gazetted officer.</li>
                    <li>The attester will have to write his/her CNIC No./ Contact No. besides affixing by-name official stamp on the form.</li>
                    <li>On production of data form (duly attested) the deferred token of minor will be allowed go-ahead.</li>
					<li>After allowing go-ahead by Assistant Director, the applicant may leave the Passport Office, as the process is complete, by taking token generated at Step 2.</li>
					<li>In case the matter is deferred due to some additional documents or case referred to the Security Agency for determination of National Status by the Assistant Director/ Officer In-charge, the applicant may also leave the office, as the remaining process will be completed upon receipt of documents/clearance report from Security Agency. The applicant would be informed upon receipt of clearance report telephonically.</li>
                </ul>
				  
