        var tr = table.getElementsByTagName("tr");
        for (var i = 0; i < tr.length; i++) {
            var tdColumn2 = tr[i].getElementsByTagName("td")[1]; // Column 2
            var tdColumn4 = tr[i].getElementsByTagName("td")[3]; // Column 4
            var txtValueColumn2 = tdColumn2 ? (tdColumn2.textContent || tdColumn2.innerText) : "";
            var txtValueColumn4 = tdColumn4 ? (tdColumn4.textContent || tdColumn4.innerText) : "";
            
            // Check if the filter matches either column 2 or column 4
            if (
                txtValueColumn2.toUpperCase().indexOf(filter) > -1 || 
                txtValueColumn4.toUpperCase().indexOf(filter) > -1
            ) {
                tr[i].style.display = ""; // Show row
            } else {
                tr[i].style.display = "none"; // Hide row
            }
        }
    });
};
